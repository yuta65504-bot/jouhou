export function labById(id: string): Lab | undefined {
  return LABS.find((lab) => lab.id === id)
}

export function labsByField(fieldId: string): Lab[] {
  return LABS.filter((lab) => lab.fieldId === fieldId)
}

/** 「今日の実験」を日付から決定的に選ぶ */
export function pickTodaysLab(): Lab {
  return LABS[dateHash(todayJst(), LABS.length)]
}
